package cybershield.monitoring;

import cybershield.network.VirtualNetwork;
import cybershield.security.SecurityEvent;
import cybershield.security.Severity;

import java.util.ArrayList;
import java.util.Collection;
import java.util.Collections;
import java.util.List;

/**
 * SecurityMonitor — CyberShield Arena Phase 4
 *
 * Responsibilities:
 *   1. Receives events into an EventProcessor queue.
 *   2. Evaluates queued events against RuleBasedDetectionEngine.
 *   3. Calculates explainable risk scores (0–100) via RiskScorer.
 *   4. Generates and stores deduplicated SecurityAlert instances in AlertManager.
 *   5. Persists processed events to CSV audit logs via EventLogger.
 *   6. Displays a security monitoring summary.
 */
public class SecurityMonitor {

    private final VirtualNetwork network;
    private final EventProcessor eventProcessor;
    private final RuleBasedDetectionEngine detectionEngine;
    private final AlertManager alertManager;
    private final RiskScorer riskScorer;
    private final EventLogger eventLogger;

    public SecurityMonitor(VirtualNetwork network) {
        this(network, new EventLogger());
    }

    public SecurityMonitor(VirtualNetwork network, EventLogger eventLogger) {
        this.network = network;
        this.eventProcessor = new EventProcessor();
        this.detectionEngine = new RuleBasedDetectionEngine();
        this.alertManager = new AlertManager();
        this.riskScorer = new RiskScorer();
        this.eventLogger = (eventLogger != null) ? eventLogger : new EventLogger();

        // Register default industry-standard baseline detection rules
        detectionEngine.registerRule(new BruteForceDetectionRule(10));
        detectionEngine.registerRule(new PortScanDetectionRule(10, 5));
        detectionEngine.registerRule(new SuspiciousConnectionRule(5, 10));
    }

    /**
     * Ingests a collection of security events into the monitor's processing queue.
     *
     * @param events events generated by SimulationEngine or attack agents
     */
    public void ingestEvents(Collection<SecurityEvent> events) {
        if (events != null) {
            eventProcessor.enqueueAll(events);
        }
    }

    /**
     * Ingests a single security event.
     */
    public void ingestEvent(SecurityEvent event) {
        if (event != null) {
            eventProcessor.enqueue(event);
        }
    }

    /**
     * Processes all pending events in the queue:
     *   - Evaluates detection rules
     *   - Calculates risk scores
     *   - Generates alerts
     *   - Writes audit CSV logs
     *
     * @return count of processed events
     */
    public int processPendingEvents() {
        System.out.println("\n[PROCESSOR] Processing generated events from queue (" +
                eventProcessor.getPendingCount() + " pending)...");

        List<SecurityEvent> processedInCycle = new ArrayList<>();

        int count = eventProcessor.processAll(event -> {
            processedInCycle.add(event);
            System.out.println("[EVENT] " + event.getAttackType() + " | " +
                    event.getSourceNodeId() + " -> " + event.getTargetNodeId() +
                    " (" + event.getEventId() + ")");

            List<DetectionResult> matches = detectionEngine.evaluateEvent(event);

            if (matches.isEmpty()) {
                System.out.println("  [DETECTION] No configured rule matched.");
                System.out.println("  [RESULT] Event recorded without a maliciousness claim.");
            } else {
                for (DetectionResult match : matches) {
                    System.out.println("  [DETECTION] Rule matched: " + match.getRuleId() +
                            " (" + match.getExplanation() + ")");

                    // Calculate risk score
                    int score = riskScorer.calculateScore(event, match, network);

                    // Create alert
                    String alertTitle = formatAlertTitle(event, match);
                    SecurityAlert alert = new SecurityAlert(
                            event.getEventId(),
                            event.getSourceNodeId(),
                            event.getTargetNodeId(),
                            alertTitle,
                            match.getExplanation(),
                            match.getRecommendedSeverity(),
                            score,
                            Collections.singletonList(match.getRuleId())
                    );

                    boolean added = alertManager.addAlert(alert);
                    if (added) {
                        System.out.println("  [ALERT] " + alert.getAlertTitle());
                        System.out.println("  [SEVERITY] " + alert.getSeverity());
                        System.out.println("  [RISK SCORE] " + alert.getRiskScore() + "/100");
                    }
                }
            }
        });

        // Persist processed events to CSV log
        int logged = eventLogger.logEvents(processedInCycle);
        System.out.printf("[LOGGER] %d event(s) saved to %s\n", logged, eventLogger.getLogFilePath());

        return count;
    }

    private String formatAlertTitle(SecurityEvent event, DetectionResult result) {
        return switch (event.getAttackType()) {
            case LOGIN_ATTACK -> "Repeated login failures detected (Brute-Force)";
            case PORT_SCAN -> "Unusual port-scanning reconnaissance detected";
            case SUSPICIOUS_CONNECTION -> "Anomalous network connection activity detected";
        };
    }

    /**
     * Renders a comprehensive security monitoring summary.
     */
    public void displayMonitoringSummary() {
        System.out.println("\n+------------------------------------------------------------------------------------+");
        System.out.printf("| %-82s |\n", "SECURITY MONITORING & THREAT DETECTION SUMMARY");
        System.out.println("+------------------------------------------------------------------------------------+");
        System.out.printf("  Total Events Processed : %d\n", eventProcessor.getTotalProcessedCount());
        System.out.printf("  Total Alerts Raised    : %d\n", alertManager.getTotalAlertCount());
        System.out.println("------------------------------------------------------------------------------------");
        System.out.printf("  Critical-Severity Alerts: %d\n", alertManager.getAlertCountBySeverity(Severity.CRITICAL));
        System.out.printf("  High-Severity Alerts    : %d\n", alertManager.getAlertCountBySeverity(Severity.HIGH));
        System.out.printf("  Medium-Severity Alerts  : %d\n", alertManager.getAlertCountBySeverity(Severity.MEDIUM));
        System.out.printf("  Low-Severity Alerts     : %d\n", alertManager.getAlertCountBySeverity(Severity.LOW));
        System.out.println("+------------------------------------------------------------------------------------+\n");
    }

    // ---------------------------------------------------------------
    // Component Accessors
    // ---------------------------------------------------------------

    public EventProcessor getEventProcessor() {
        return eventProcessor;
    }

    public RuleBasedDetectionEngine getDetectionEngine() {
        return detectionEngine;
    }

    public AlertManager getAlertManager() {
        return alertManager;
    }

    public RiskScorer getRiskScorer() {
        return riskScorer;
    }

    public EventLogger getEventLogger() {
        return eventLogger;
    }
}
