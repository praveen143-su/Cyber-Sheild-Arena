package cybershield.ml;

import cybershield.monitoring.DetectionResult;
import cybershield.monitoring.RuleBasedDetectionEngine;
import cybershield.security.AttackType;
import cybershield.security.SecurityEvent;
import cybershield.security.Severity;
import weka.core.Instances;

import java.time.Instant;
import java.util.ArrayList;
import java.util.List;

/**
 * DetectionComparison — CyberShield Arena Phase 5
 *
 * OOP Concepts demonstrated:
 *   - Dependency Injection  : Both detectors are injected — neither is constructed internally.
 *   - Separation of Concerns : Comparison logic is completely separate from both detectors.
 *   - Fairness principle     : Both methods receive the same feature information so the
 *                              comparison is not biased towards either approach.
 *
 * ─── Two types of comparison ─────────────────────────────────────────────────
 *
 *  A) compareOnTestData(testInstances)
 *     Uses the held-out CSV test split.  Ground truth = CSV label.
 *     Computes accuracy for both methods on the same labelled examples.
 *     This is the rigorous, fair evaluation.
 *
 *  B) compareOnSimulatedEvents(events, mlPredictions)
 *     Uses events generated by Phase 3 SimulationEngine.
 *     These have no ground-truth label so we can only show AGREEMENT/DISAGREEMENT,
 *     not measure accuracy.  Useful for a visual side-by-side comparison.
 *
 * ─── IMPORTANT caveat ────────────────────────────────────────────────────────
 * Rule-based alerts are NOT used as ground truth because the rules themselves are
 * imperfect detectors.  Using rule output as ground truth would create a circular
 * comparison that unfairly disadvantages the ML model.
 */
public class DetectionComparison {

    private final RuleBasedDetectionEngine ruleEngine;
    private final MLDetectionEngine mlEngine;
    private final MLFeatureExtractor featureExtractor = new MLFeatureExtractor();

    // ── Results from compareOnTestData() ──
    private int mlCorrect   = 0;
    private int ruleCorrect = 0;
    private int totalTest   = 0;
    private final List<String> bothDetected     = new ArrayList<>();
    private final List<String> mlOnlyDetected   = new ArrayList<>();
    private final List<String> ruleOnlyDetected = new ArrayList<>();
    private final List<String> bothMissed       = new ArrayList<>();
    private boolean testComparisonRun = false;

    // ---------------------------------------------------------------
    // Constructor
    // ---------------------------------------------------------------

    public DetectionComparison(RuleBasedDetectionEngine ruleEngine, MLDetectionEngine mlEngine) {
        if (ruleEngine == null || mlEngine == null) {
            throw new IllegalArgumentException("Rule engine and ML engine must not be null.");
        }
        this.ruleEngine = ruleEngine;
        this.mlEngine   = mlEngine;
    }

    // ---------------------------------------------------------------
    // A) Rigorous comparison on labelled test split
    // ---------------------------------------------------------------

    /**
     * Compares both detectors on the held-out test split of the CSV dataset.
     *
     * For each test instance:
     *   1. Read the ground-truth label from the Weka Instances class attribute.
     *   2. Reconstruct a pseudo-SecurityEvent from the numeric features (same values, placeholder IDs).
     *   3. Run the rule-based engine on the pseudo-event.
     *   4. Run the ML model on the same features.
     *   5. Record which was correct.
     *
     * @param testInstances the held-out Weka Instances (with class labels)
     */
    public void compareOnTestData(Instances testInstances) {
        if (testInstances == null || testInstances.isEmpty()) {
            System.err.println("[Comparison] Test instances are null or empty — skipping.");
            return;
        }

        resetResults();

        for (int i = 0; i < testInstances.size(); i++) {
            weka.core.Instance inst = testInstances.instance(i);
            String groundTruth = testInstances.classAttribute().value((int) inst.classValue());
            boolean actualSuspicious = PredictionClass.SUSPICIOUS.name().equals(groundTruth);

            // Extract feature values directly from the Weka instance
            double[] features = new double[MLFeatureExtractor.FEATURE_COUNT];
            for (int j = 0; j < MLFeatureExtractor.FEATURE_COUNT; j++) {
                features[j] = inst.value(j);
            }

            // Build a pseudo-SecurityEvent for the rule-based engine
            // (rules need a SecurityEvent object; placeholder node IDs are used since they are not features)
            SecurityEvent pseudoEvent = buildPseudoEvent(features, i);

            // ─ ML prediction ────────────────────────────────────────
            ThreatPrediction mlPred;
            try {
                mlPred = mlEngine.getModel().predict("TEST-" + i, features);
            } catch (Exception e) {
                System.err.printf("[Comparison] ML prediction failed for test instance %d: %s%n", i, e.getMessage());
                continue;
            }
            boolean mlSaidSuspicious = mlPred.getPredictedClass() == PredictionClass.SUSPICIOUS;

            // ─ Rule-based prediction ─────────────────────────────────
            List<DetectionResult> ruleMatches = ruleEngine.evaluateEvent(pseudoEvent);
            boolean ruleSaidSuspicious = !ruleMatches.isEmpty();

            // ─ Score each method ─────────────────────────────────────
            if (mlSaidSuspicious == actualSuspicious)   mlCorrect++;
            if (ruleSaidSuspicious == actualSuspicious) ruleCorrect++;
            totalTest++;

            // ─ Categorise detection outcome (only for actual SUSPICIOUS events) ─
            String label = String.format("Test[%d] GT=%s", i, groundTruth);
            if (actualSuspicious) {
                if      (mlSaidSuspicious && ruleSaidSuspicious) bothDetected.add(label);
                else if (mlSaidSuspicious)                       mlOnlyDetected.add(label);
                else if (ruleSaidSuspicious)                     ruleOnlyDetected.add(label);
                else                                             bothMissed.add(label);
            }
        }

        testComparisonRun = true;
        System.out.printf("[Comparison] Test comparison complete. %d examples evaluated.%n", totalTest);
    }

    // ---------------------------------------------------------------
    // B) Side-by-side agreement analysis on simulated events
    // ---------------------------------------------------------------

    /**
     * Displays a side-by-side table comparing rule-based and ML decisions on
     * the Phase 3 simulated events.
     *
     * Note: Since simulated events carry no ground-truth label, this is an
     * agreement analysis — it shows where the two methods agree or differ,
     * but cannot measure which is correct.
     *
     * @param simulatedEvents  events from SimulationEngine
     * @param mlPredictions    ML predictions already computed for these events
     */
    public void compareOnSimulatedEvents(List<SecurityEvent> simulatedEvents,
                                          List<ThreatPrediction> mlPredictions) {
        if (simulatedEvents == null || mlPredictions == null
                || simulatedEvents.size() != mlPredictions.size()) {
            System.err.println("[Comparison] Mismatched or null inputs — skipping simulated-event comparison.");
            return;
        }

        System.out.println("\n--- Agreement Analysis: Phase 3 Simulated Events ---");
        System.out.printf("%-12s | %-22s | %-15s | %-15s | %s%n",
                "Event ID", "Attack Type", "Rule-Based", "ML Prediction", "Agreement?");
        System.out.println("-".repeat(85));

        for (int i = 0; i < simulatedEvents.size(); i++) {
            SecurityEvent event  = simulatedEvents.get(i);
            ThreatPrediction ml  = mlPredictions.get(i);

            List<DetectionResult> ruleMatches = ruleEngine.evaluateEvent(event);
            String ruleResult = ruleMatches.isEmpty() ? "NORMAL" : "SUSPICIOUS";
            String mlResult   = ml.getPredictedClass().name();
            String agreement  = ruleResult.equals(mlResult) ? "✓ Agree" : "✗ Differ";

            System.out.printf("%-12s | %-22s | %-15s | %-15s | %s%n",
                    event.getEventId(),
                    event.getAttackType().name(),
                    ruleResult,
                    mlResult,
                    agreement);
        }
        System.out.println("-".repeat(85));
    }

    // ---------------------------------------------------------------
    // Display test-data comparison report
    // ---------------------------------------------------------------

    /**
     * Prints the detailed comparison report after compareOnTestData() has been called.
     */
    public void displayComparisonReport() {
        if (!testComparisonRun) {
            System.out.println("[Comparison] No test-data comparison run yet.");
            return;
        }

        double mlAcc   = totalTest > 0 ? (double) mlCorrect   / totalTest : 0.0;
        double ruleAcc = totalTest > 0 ? (double) ruleCorrect / totalTest : 0.0;

        System.out.println("\n========================================");
        System.out.println("     DETECTION METHOD COMPARISON        ");
        System.out.println("========================================");
        System.out.printf("  Test examples evaluated : %d%n%n", totalTest);
        System.out.printf("  Rule-Based Detector accuracy : %.4f  (%.1f%%)%n", ruleAcc, ruleAcc * 100);
        System.out.printf("  ML Detector accuracy         : %.4f  (%.1f%%)%n", mlAcc,   mlAcc   * 100);
        System.out.println();
        System.out.printf("  SUSPICIOUS events caught by BOTH          : %d%n", bothDetected.size());
        System.out.printf("  SUSPICIOUS events caught by ML only       : %d%n", mlOnlyDetected.size());
        System.out.printf("  SUSPICIOUS events caught by Rules only    : %d%n", ruleOnlyDetected.size());
        System.out.printf("  SUSPICIOUS events missed by BOTH          : %d%n", bothMissed.size());

        if (!mlOnlyDetected.isEmpty()) {
            System.out.println("\n  Caught by ML but not by rules:");
            mlOnlyDetected.forEach(s -> System.out.println("    " + s));
        }
        if (!ruleOnlyDetected.isEmpty()) {
            System.out.println("\n  Caught by rules but not by ML:");
            ruleOnlyDetected.forEach(s -> System.out.println("    " + s));
        }
        if (!bothMissed.isEmpty()) {
            System.out.println("\n  Missed by BOTH detectors:");
            bothMissed.forEach(s -> System.out.println("    " + s));
        }

        System.out.println("========================================\n");
    }

    // ---------------------------------------------------------------
    // Private helpers
    // ---------------------------------------------------------------

    /**
     * Reconstructs a minimal SecurityEvent from numeric feature values.
     * Used to feed the rule-based engine during test-data comparison.
     * Placeholder source/target node IDs are used — they are NOT features.
     */
    private SecurityEvent buildPseudoEvent(double[] features, int index) {
        int failedLogins   = (int) features[0];
        int connAttempts   = (int) features[1];
        int uniquePorts    = (int) features[2];
        int severityLevel  = (int) features[3];
        int attackTypeCode = (int) features[4];

        AttackType attackType = MLFeatureExtractor.decodeAttackType(attackTypeCode);
        Severity severity = switch (severityLevel) {
            case 1  -> Severity.LOW;
            case 2  -> Severity.MEDIUM;
            case 3  -> Severity.HIGH;
            case 4  -> Severity.CRITICAL;
            default -> Severity.MEDIUM;
        };

        return new SecurityEvent(
            "TEST-" + index,
            Instant.now(),
            attackType,
            "CMP-SRC",   // placeholder — not a feature
            "CMP-TGT",   // placeholder — not a feature
            "Comparison pseudo-event #" + index,
            severity,
            failedLogins,
            connAttempts,
            uniquePorts
        );
    }

    private void resetResults() {
        mlCorrect   = 0; ruleCorrect = 0; totalTest = 0;
        bothDetected.clear(); mlOnlyDetected.clear();
        ruleOnlyDetected.clear(); bothMissed.clear();
        testComparisonRun = false;
    }

    // ── Simple getters for external reporting ──
    public int getMlCorrect()   { return mlCorrect; }
    public int getRuleCorrect() { return ruleCorrect; }
    public int getTotal()       { return totalTest; }
}
